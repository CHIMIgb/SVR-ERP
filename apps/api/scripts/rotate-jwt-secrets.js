const c = require('node:crypto');
const fs = require('node:fs');
const p = 'C:/Users/chimi/DOcuments/Github/SVR-ERP/apps/api/.env';
let s = fs.readFileSync(p, 'utf8');
const a = c.randomBytes(48).toString('base64url');
const r = c.randomBytes(48).toString('base64url');
s = s.replace(/JWT_ACCESS_SECRET=.*/, 'JWT_ACCESS_SECRET="' + a + '"');
s = s.replace(/JWT_REFRESH_SECRET=.*/, 'JWT_REFRESH_SECRET="' + r + '"');
fs.writeFileSync(p, s);
console.log('rotados: access=' + a.slice(0, 10) + '..., refresh=' + r.slice(0, 10) + '...');
